def doc_to_text(doc) -> str:
    """Return the premise for NLI task."""
    return doc["prompts"][0]["sentence1"]


def doc_to_target(doc) -> int:
    """
    Map text_label to the index of the correct choice (0, 1, or 2).
    This matches the XNLI pattern where doc_to_target returns an integer index.
    """
    text_label = doc.get("text_label", "").strip().lower()
    label_to_index = {
        "entailment": 0,
        "neutral": 1,
        "contradiction": 2,
    }
    return label_to_index.get(text_label, 1)


def gen_lang_yamls(output_dir: str, overwrite: bool) -> None:
    """
    Generate a yaml file for each language in NLR-NLI.
    Each file includes the common config and adds language-specific question
    words and answer labels in the doc_to_choice template.

    :param output_dir: The directory to output the files to.
    :param overwrite: Whether to overwrite files if they already exist.
    """
    err = []
    for lang_code in LANGUAGES.keys():
        file_name = f"aisg_nlr_nli_{lang_code}.yaml"
        lang_cfg = LANGUAGES[lang_code]
        
        try:
            with open(
                f"{output_dir}/{file_name}", "w" if overwrite else "x", encoding="utf8"
            ) as f:
                f.write("# Generated by utils.py\n")
                f.write(f"dataset_name: {lang_code}\n")
                # Jinja2 template that builds three answer options with language-specific text
                # Format: "Premise, <question_word>? <answer_option>, Hypothesis"
                # Use double quotes to wrap so single quotes inside don't break the string
                doc_to_choice_template = (
                    "{{["
                    f"prompts[0].sentence1 + ', {lang_cfg['question_word']}? {lang_cfg['answer_yes']}, ' + prompts[0].sentence2, "
                    f"prompts[0].sentence1 + ', {lang_cfg['question_word']}? {lang_cfg['answer_maybe']}, ' + prompts[0].sentence2, "
                    f"prompts[0].sentence1 + ', {lang_cfg['question_word']}? {lang_cfg['answer_no']}, ' + prompts[0].sentence2"
                    "]}}"
                )
                f.write(f'doc_to_choice: "{doc_to_choice_template}"\n')
                f.write("doc_to_text: ''\n")
                f.write("include: aisg_nlr_nli_common_yaml\n")
                f.write(f"task: aisg_nlr_nli_{lang_code}\n")
        except FileExistsError:
            err.append(file_name)

    if len(err) > 0:
        print(
            f"Note: {len(err)} files already exist (use --overwrite flag to update): {', '.join(err)}"
        )


def main() -> None:
    """Parse CLI args and generate language-specific yaml files."""
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--overwrite",
        default=False,
        action="store_true",
        help="Overwrite files if they already exist",
    )
    parser.add_argument(
        "--output-dir", default=".", help="Directory to write yaml files to"
    )
    args = parser.parse_args()

    gen_lang_yamls(output_dir=args.output_dir, overwrite=args.overwrite)


if __name__ == "__main__":
    main()

