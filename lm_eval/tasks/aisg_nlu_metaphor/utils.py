import argparse

import yaml


# Languages in metaphor identification dataset
# Binary classification: choice A vs choice B
LANGUAGES = {
    "id": "Indonesian",
    "ta": "Tamil",
}


def gen_lang_yamls(output_dir: str, overwrite: bool) -> None:
    """
    Generate a yaml file for each language.

    :param output_dir: The directory to output the files to.
    :param overwrite: Whether to overwrite files if they already exist.
    """
    err = []
    for lang in LANGUAGES.keys():
        file_name = f"aisg_nlu_metaphor_{lang}.yaml"
        try:
            with open(
                f"{output_dir}/{file_name}", "w" if overwrite else "x", encoding="utf8"
            ) as f:
                f.write("# Generated by utils.py\n")
                yaml.dump(
                    {
                        "include": "aisg_nlu_metaphor_common_yaml",
                        "dataset_name": lang,
                        "task": f"aisg_nlu_metaphor_{lang}",
                        "doc_to_text": "{{prompts[0].phrase}}",
                        "doc_to_choice": "!function utils.doc_to_choice",
                    },
                    f,
                    allow_unicode=True,
                )
        except FileExistsError:
            err.append(file_name)

    if len(err) > 0:
        raise FileExistsError(
            "Files were not created because they already exist (use --overwrite flag):"
            f" {', '.join(err)}"
        )


def metaphor_label_to_index(doc: dict) -> int:
    """
    Indonesian metaphor task: map label 'A' or 'B' to 0 or 1.
    
    A (choice1) → 0
    B (choice2) → 1
    """
    label = doc.get("label", "").strip().upper()
    return 0 if label == "A" else 1


def metaphor_truth_to_index(doc: dict) -> int:
    """
    Tamil metaphor task: map label 'true' or 'false' to 0 or 1.
    
    'true' → 0 (has valid interpretation)
    'false' → 1 (has invalid interpretation)
    """
    label = doc.get("label", "").strip().lower()
    return 0 if label == "true" else 1


def main() -> None:
    """Parse CLI args and generate language-specific yaml files."""
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--overwrite",
        default=False,
        action="store_true",
        help="Overwrite files if they already exist",
    )
    parser.add_argument(
        "--output-dir", default=".", help="Directory to write yaml files to"
    )
    args = parser.parse_args()

    gen_lang_yamls(output_dir=args.output_dir, overwrite=args.overwrite)


if __name__ == "__main__":
    main()
